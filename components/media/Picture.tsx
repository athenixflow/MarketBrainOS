import React from 'react';
import type { ImageAsset } from './types';

/* React 18 does not recognise the camelCase `fetchPriority` prop (it warns and may drop it); the
   lowercase HTML attribute is passed through as-is, prerendered HTML included. */
export const fetchPriorityAttr = (value: 'high' | 'low' | 'auto') => ({ fetchpriority: value } as Record<string, string>);

interface PictureProps {
  asset: ImageAsset;
  /** Rendered width hint for the browser's srcset selection, e.g. "(min-width: 1024px) 50vw, 100vw". */
  sizes?: string;
  /** Above-the-fold images should be eager; everything else lazy (default). */
  priority?: boolean;
  className?: string;
  imgClassName?: string;
}

/**
 * Responsive <picture>: avif -> webp -> jpg, explicit width/height so the layout never shifts while it loads.
 * Assets come from assets/media/index.ts (generated by `npm run media:optimize`).
 */
const Picture: React.FC<PictureProps> = ({ asset, sizes = '100vw', priority = false, className = '', imgClassName = '' }) => (
  <picture className={`block ${className}`}>
    {asset.sources.map((s) => (
      <source key={s.type} type={s.type} srcSet={s.srcSet} sizes={sizes} />
    ))}
    <img
      src={asset.fallback}
      alt={asset.alt}
      width={asset.width}
      height={asset.height}
      loading={priority ? 'eager' : 'lazy'}
      decoding="async"
      {...fetchPriorityAttr(priority ? 'high' : 'auto')}
      className={`block w-full h-auto ${imgClassName}`}
    />
  </picture>
);

export default Picture;
